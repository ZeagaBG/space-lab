const zones = document.querySelectorAll('.interactive-zone');
const planetName = document.getElementById('planet-name');
const planetDescription = document.getElementById('planet-description');
const infoCard = document.getElementById('info-card');

zones.forEach(zone => {
    zone.addEventListener('click', () => {
        const planetKey = zone.getAttribute('data-planet');
        const data = planetData[planetKey];

        if (data) {
            // Плавна анимация при промяна на съдържанието
            infoCard.style.opacity = 0;
            
            setTimeout(() => {
                planetName.textContent = data.name;
                planetDescription.innerHTML = data.description;
                infoCard.style.opacity = 1;
            }, 250);
        }
    });
});
